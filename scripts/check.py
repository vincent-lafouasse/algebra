"""Progress report: which declarations in Base/ and Algebra/ are proved, per file.

    uv run scripts/check.py                  # per-file table + anything tainted
    uv run scripts/check.py Algebra/Group    # only files under a path
    uv run scripts/check.py -v               # also list every stub
    uv run scripts/check.py -a               # also list what uses `Quot.sound` and choice

A declaration is
* proved   if it uses no `sorry`, directly or through anything it depends on;
* a stub   if its own source contains `sorry`: expected, it's unfinished;
* TAINTED  if it has no `sorry` of its own but uses something that does: a proof you may
           think is finished, which is only as good as the stub it leans on.

Counts theorems and definitions (named instances included); names generated by attributes or
commands (`ext_iff`, anonymous instance names, …) are not counted.

Also reports the axioms that proved declarations rest on. Lean has three, all legitimate:
`propext` (equivalent propositions are equal), `Quot.sound` (quotients; `funext` is proved from
it) and `Classical.choice` (the axiom of choice: `Classical.choose`, `byContradiction`, `em`,
everything `noncomputable`). Any other axiom is something declared with `axiom` in the
library, and is reported in red.

Exits 1 if anything is tainted or rests on a non-standard axiom.

Unlike `api.py` this needs Lean: whether a proof leans on a `sorry` elsewhere is only known
from the compiled terms (`collectAxioms`), not from the source.
"""

import hashlib
import os
import subprocess
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# For each hand-written declaration: status, kind, name, file, line, and its axioms other than
# `sorryAx`, comma-separated (tab-separated).
LEAN = r"""
import Lean
import Base
import Algebra
open Lean Elab Command in
#eval show CommandElabM Unit from do
  let env ← getEnv
  let mut files : Std.HashMap String (Array String) := {}
  for (n, ci) in env.constants.map₁.toList do
    unless (`My).isPrefixOf n && !n.isInternal do continue
    let kind ← match ci with
      | .thmInfo _ => pure "theorem"
      | .defnInfo _ | .opaqueInfo _ => pure "def"
      | _ => continue
    if env.isProjectionFn n then continue
    let some idx := env.getModuleIdxFor? n | continue
    let path := (env.header.moduleNames[idx.toNat]!).toString.replace "." "/" ++ ".lean"
    let some r ← liftCoreM (findDeclarationRanges? n) | continue
    let lines ← match files[path]? with
      | some ls => pure ls
      | none => do
        let ls ← IO.FS.lines path
        files := files.insert path ls
        pure ls
    let src := lines.extract (r.range.pos.line - 1) r.range.endPos.line
    -- generated by an attribute or a command: its name is not in its source
    unless src.any (·.contains n.getString!) do continue
    let axioms ← liftCoreM (collectAxioms n)
    let usesSorry := axioms.contains ``sorryAx
    let others := axioms.filter (· != ``sorryAx) |>.map toString |>.toList
    let status :=
      if src.any (·.contains "sorry") then "stub"
      else if usesSorry then "tainted"
      else "proved"
    IO.println s!"{status}\t{kind}\t{n}\t{path}\t{r.range.pos.line}\t{",".intercalate others}"
"""


Row = tuple[str, str, str, str, int, list[str]]

# Lean's own axioms; anything else was declared in the library
STANDARD = ["propext", "Quot.sound", "Classical.choice"]


# The Lean output depends only on these, so it is cached under their hash: an unchanged tree
# skips the build check and the Lean run (about 3 s, mostly `import Lean`). In `.lake/`, which
# git ignores and `lake clean` removes.
CACHE = ROOT / ".lake" / "check-cache.tsv"


def source_hash() -> str:
    h = hashlib.sha256(LEAN.encode())
    files = [ROOT / n for n in ("lean-toolchain", "lakefile.toml", "Base.lean", "Algebra.lean")]
    files += sorted(p for d in ("Base", "Algebra") for p in (ROOT / d).rglob("*.lean"))
    for p in files:
        h.update(str(p.relative_to(ROOT)).encode() + b"\0" + p.read_bytes() + b"\0")
    return h.hexdigest()


def lean_output() -> str:
    key = source_hash()
    try:
        cached_key, cached = CACHE.read_text().split("\n", 1)
        if cached_key == key:
            return cached
    except (OSError, ValueError):
        pass
    # build first, straight to the terminal (so lake keeps its colors and progress bar): after
    # an edit low in the import graph this is most of the running time. `--log-level=error`
    # hides the `sorry` warnings, which this report counts anyway.
    build = ["lake", "build", "--log-level=error", "Base", "Algebra"]
    if subprocess.run(build, cwd=ROOT).returncode != 0:
        sys.exit("check: build failed")
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "Check.lean"
        src.write_text(LEAN)
        res = subprocess.run(
            ["lake", "env", "lean", str(src)], cwd=ROOT, capture_output=True, text=True
        )
    if res.returncode != 0:
        sys.exit(res.stdout + res.stderr)
    CACHE.parent.mkdir(exist_ok=True)
    CACHE.write_text(key + "\n" + res.stdout)
    return res.stdout


def run_lean() -> list[Row]:
    rows = []
    for line in lean_output().splitlines():
        status, kind, name, path, lineno, axioms = line.split("\t")
        rows.append((status, kind, name, path, int(lineno), axioms.split(",") if axioms else []))
    # Base first: it comes first in the import graph
    return sorted(rows, key=lambda r: (not r[3].startswith("Base"), r[3], r[4]))


# colors only on a terminal, and not if NO_COLOR is set (https://no-color.org)
COLOR = sys.stdout.isatty() and "NO_COLOR" not in os.environ


def paint(text: str, code: str) -> str:
    return f"\033[{code}m{text}\033[0m" if COLOR else text


GREEN, YELLOW, RED, BOLD, DIM = "32", "33", "31", "1", "2"


def frac(done: int, total: int) -> str:
    """`done / total`, green when finished, yellow when started, dim when not started."""
    if not total:
        return " " * 9
    text = f"{done:>3} / {total:<3}"
    return paint(text, GREEN if done == total else YELLOW if done else DIM)


def main() -> None:
    args = sys.argv[1:]
    verbose = "-v" in args
    show_choice = "-a" in args
    prefixes = [a.rstrip("/") for a in args if a not in ("-v", "-a")]

    rows = [
        r for r in run_lean() if not prefixes or any(r[3].startswith(p) for p in prefixes)
    ]

    # per file, per kind: [proved, total]; and tainted per file
    table: dict[str, dict[str, list[int]]] = defaultdict(
        lambda: {"theorem": [0, 0], "def": [0, 0]}
    )
    ntainted: dict[str, int] = defaultdict(int)
    nchoice: dict[str, int] = defaultdict(int)
    for status, kind, _, path, _, axioms in rows:
        table[path][kind][1] += 1
        if status == "proved":
            table[path][kind][0] += 1
            if "Classical.choice" in axioms:
                nchoice[path] += 1
        elif status == "tainted":
            ntainted[path] += 1

    width = max([len(p) for p in table] + [5])
    print(paint(f"\n{'':<{width}}   theorems      defs", BOLD))
    totals = {"theorem": [0, 0], "def": [0, 0]}
    for path, kinds in table.items():
        t, d = kinds["theorem"], kinds["def"]
        mark = paint("  ✓", GREEN) if t[0] == t[1] and d[0] == d[1] else ""
        if ntainted[path]:
            mark += paint(f"  {ntainted[path]} tainted", RED)
        if nchoice[path]:
            mark += paint(f"  {nchoice[path]} use choice", DIM)
        print(f"{path:<{width}}   {frac(*t)}   {frac(*d)}{mark}")
        for k in totals:
            totals[k][0] += kinds[k][0]
            totals[k][1] += kinds[k][1]
    label = paint(f"{'total':<{width}}", BOLD)
    print(f"{label}   {frac(*totals['theorem'])}   {frac(*totals['def'])}")

    # the axioms proved declarations rest on: how many use each
    proved = [r for r in rows if r[0] == "proved"]
    used = {a: sum(a in r[5] for r in proved) for a in STANDARD}
    print("\naxioms used by proved declarations: " + ", ".join(f"{a} {n}" for a, n in used.items()))

    def listing(rs: list[Row]) -> list[str]:
        return [f"  {n:<45} {p}:{l}" for _, _, n, p, l, _ in rs]

    stubs = listing([r for r in rows if r[0] == "stub"])
    tainted = listing([r for r in rows if r[0] == "tainted"])
    foreign = [r for r in rows if any(a not in STANDARD for a in r[5])]
    if verbose and stubs:
        print(paint("\nstubs:", BOLD), *stubs, sep="\n")
    if show_choice:
        # `propext` is behind every `rw` with an `↔`: its list would be noise, the count is enough
        for axiom, what in [("Quot.sound", "quotients, and `funext`"),
                            ("Classical.choice", "the axiom of choice")]:
            users = listing([r for r in proved if axiom in r[5]])
            print(paint(f"\nusing {axiom} ({what}):", BOLD), *(users or ["  (none)"]), sep="\n")
    if foreign:
        lines = [f"  {n:<45} {p}:{l}  ({', '.join(a for a in ax if a not in STANDARD)})"
                 for _, _, n, p, l, ax in foreign]
        print(paint("\nNON-STANDARD AXIOMS (declared with `axiom` in the library):", RED), *lines, sep="\n")
    if tainted or foreign:
        print(paint("\nTAINTED (no sorry of their own, but depend on one):", RED), *tainted, sep="\n")
        print("  find the culprit with: #print axioms <name>")
        print(paint(f"\ncheck: {len(tainted)} tainted, {len(foreign)} non-standard axioms, "
                    f"{len(stubs)} stubs", RED))
        sys.exit(1)
    print(paint(f"\ncheck: ok ({len(stubs)} stubs, nothing else depends on sorry)", GREEN))


if __name__ == "__main__":
    main()
